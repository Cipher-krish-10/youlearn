import type { TranscriptProvider } from "@/core/interfaces/transcript-provider";
import type { TranscriptResult } from "@/core/types/transcript";
import { TranscriptUnavailableError } from "@/core/errors/provider-errors";
import {
  SAMPLE_YOUTUBE_ID,
  sampleTranscript,
} from "@/core/providers/transcript/sample-data";

/**
 * Returns a bundled transcript for the sample video only. Useful for local
 * development and tests with no external dependency. Real videos decline.
 */
export class MockTranscriptProvider implements TranscriptProvider {
  readonly name = "mock";

  async getTranscript(videoId: string): Promise<TranscriptResult> {
    if (videoId !== SAMPLE_YOUTUBE_ID) {
      throw new TranscriptUnavailableError(
        "No bundled transcript for this video.",
        "mock",
      );
    }
    return { segments: sampleTranscript, language: "en", isAutoGenerated: false };
  }

  async hasTranscript(videoId: string): Promise<boolean> {
    return videoId === SAMPLE_YOUTUBE_ID;
  }
}
